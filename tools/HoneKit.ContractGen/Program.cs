using System.Reflection;
using System.Text;
using System.Text.Json;
using HoneKit.Contracts;

// Turns the C# records in HoneKit.Contracts into the frontend's TypeScript types.
// Usage: dotnet run --project tools/HoneKit.ContractGen -- <out-file>
//        dotnet run --project tools/HoneKit.ContractGen -- --check <out-file>

var check = args.Contains("--check");
var outPath = args.FirstOrDefault(a => !a.StartsWith("--", StringComparison.Ordinal));

if (outPath is null)
{
    Console.Error.WriteLine("usage: HoneKit.ContractGen [--check] <out-file>");
    return 2;
}

var assembly = typeof(SkillDto).Assembly;
var nullability = new NullabilityInfoContext();
var output = new StringBuilder();

output.AppendLine("// <auto-generated>");
output.AppendLine("// Generated from src/HoneKit.Contracts by tools/HoneKit.ContractGen.");
output.AppendLine("// Do not edit. Run `npm run gen:contracts` in src/frontend after changing a contract.");
output.AppendLine("// </auto-generated>");
output.AppendLine();

var dtoTypes = assembly.GetTypes()
    .Where(t => t is { IsClass: true, IsPublic: true, Namespace: "HoneKit.Contracts" }
        && (t.Name.EndsWith("Dto", StringComparison.Ordinal)
            || t.Name.EndsWith("Request", StringComparison.Ordinal)))
    .OrderBy(t => t.Name, StringComparer.Ordinal);

foreach (var type in dtoTypes)
{
    output.AppendLine($"export interface {type.Name} {{");
    foreach (var property in type.GetProperties(BindingFlags.Public | BindingFlags.Instance))
    {
        var name = JsonNamingPolicy.CamelCase.ConvertName(property.Name);
        output.AppendLine($"  {name}: {TypeScriptType(property.PropertyType, nullability.Create(property))};");
    }
    output.AppendLine("}");
    output.AppendLine();
}

var generated = output.ToString().ReplaceLineEndings("\n");
var fullPath = Path.GetFullPath(outPath);

if (check)
{
    if (!File.Exists(fullPath))
    {
        Console.Error.WriteLine($"missing generated contracts: {fullPath}");
        return 1;
    }

    var existing = File.ReadAllText(fullPath).ReplaceLineEndings("\n");
    if (!string.Equals(existing, generated, StringComparison.Ordinal))
    {
        Console.Error.WriteLine("generated contracts are out of date: run `npm run gen:contracts`");
        return 1;
    }

    Console.WriteLine("contracts are up to date");
    return 0;
}

Directory.CreateDirectory(Path.GetDirectoryName(fullPath)!);
File.WriteAllText(fullPath, generated);
Console.WriteLine($"wrote {fullPath}");
return 0;

static string TypeScriptType(Type type, NullabilityInfo? nullability)
{
    var underlying = Nullable.GetUnderlyingType(type);
    if (underlying is not null)
    {
        return $"{TypeScriptType(underlying, null)} | null";
    }

    var mapped = type switch
    {
        var t when t == typeof(string) => "string",
        var t when t == typeof(bool) => "boolean",
        var t when t == typeof(int) || t == typeof(long) || t == typeof(double) || t == typeof(float) || t == typeof(decimal) => "number",
        var t when t == typeof(DateTimeOffset) || t == typeof(DateTime) || t == typeof(Guid) => "string",
        var t when t.IsGenericType && t.GetGenericTypeDefinition() == typeof(IReadOnlyDictionary<,>) =>
            $"Record<string, {TypeScriptType(t.GetGenericArguments()[1], nullability?.GenericTypeArguments.ElementAtOrDefault(1))}>",
        var t when t.IsArray => $"{TypeScriptType(t.GetElementType()!, nullability?.ElementType)}[]",
        var t when t.IsGenericType && t.GetGenericTypeDefinition() == typeof(IReadOnlyList<>) =>
            $"{TypeScriptType(t.GetGenericArguments()[0], nullability?.GenericTypeArguments.ElementAtOrDefault(0))}[]",
        var t when t.IsGenericType && t.GetGenericTypeDefinition() == typeof(List<>) =>
            $"{TypeScriptType(t.GetGenericArguments()[0], nullability?.GenericTypeArguments.ElementAtOrDefault(0))}[]",
        var t => t.Name
    };

    var isNullableReference = !type.IsValueType && nullability is { ReadState: NullabilityState.Nullable };
    return isNullableReference ? $"{mapped} | null" : mapped;
}
